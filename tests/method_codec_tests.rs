/// Without the feature, the error must name the method and the feature that would enable it,
/// rather than returning ciphertext-shaped garbage.
#[test]
fn without_the_feature_the_method_is_named_not_guessed() {
    // Only the fixtures whose feature is *off* are interesting here.
    #[allow(unused_mut)]
    let mut cases: Vec<(&[u8], u16, &str)> = Vec::new();
    #[cfg(not(feature = "deflate64"))]
    cases.push((SEVEN_ZIP_DEFLATE64, 9, "Deflate64"));
    #[cfg(not(feature = "lzma"))]
    cases.push((SEVEN_ZIP_LZMA, 14, "LZMA"));
    #[cfg(not(feature = "ppmd"))]
    cases.push((SEVEN_ZIP_PPMD, 98, "PPMd"));
    for (bytes, method, name) in cases {
        let supported = Compression::from_method(method).is_supported();
        if supported {
            continue;
        }
        let mut archive = Archive::new(Cursor::new(bytes.to_vec())).expect("parses");
        let error = archive.read_entry(0).unwrap_err();
        let message = error.to_string();
        assert!(
            message.contains(&method.to_string()) || message.contains(name),
            "error should identify method {method} ({name}), got: {message}"
        );
        assert!(
            matches!(error, Error::UnsupportedCompression { .. }),
            "{error:?}"
        );
    }
}

/// A corrupted payload must be an error, not a panic or a short read reported as success.
///
/// The archive structure is left intact so it still parses; only the compressed bytes are
/// damaged. This is the case that matters, because a decoder handed bad data must fail rather
/// than return whatever it managed to produce.
#[cfg(feature = "lzma")]
#[test]
fn a_corrupted_lzma_payload_is_an_error() {
    let mut bytes = SEVEN_ZIP_LZMA.to_vec();
    // The payload follows the 30-byte local header plus the 10-byte name "payload.txt".
    let payload_at = 30 + "payload.txt".len() + 9; // skip the LZMA header too
    for offset in 0..24 {
        bytes[payload_at + offset] ^= 0xFF;
    }
    let mut archive = Archive::new(Cursor::new(bytes)).unwrap();
    // The LZMA decoder runs eagerly (it drives its own output loop), so the failure surfaces when
    // the entry is opened rather than on the first read. Either surface is acceptable; silently
    // returning garbage is not.
    // `by_index` may succeed lazily and fail on read, or fail outright; both are fine, and the
    // only unacceptable outcome is a clean decode.
    let decoded_ok = match archive.by_index(0) {
        Ok(mut file) => {
            let mut out = Vec::new();
            file.read_to_end(&mut out).is_ok()
        }
        Err(_) => false,
    };
    assert!(!decoded_ok, "a corrupted payload must not decode cleanly");
}

