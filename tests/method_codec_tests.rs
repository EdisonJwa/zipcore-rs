/// A LZMA entry declares its dictionary size *inside* the stream, so it is attacker-controlled.
/// A tiny entry must not be able to ask for a multi-gigabyte allocation.
#[cfg(feature = "lzma")]
#[test]
fn rejects_an_absurd_lzma_dictionary() {
    // Patch the real 7-Zip fixture's dictionary field rather than hand-crafting a stream.
    let mut bytes = SEVEN_ZIP_LZMA.to_vec();
    let name_len = u16::from_le_bytes([bytes[26], bytes[27]]) as usize;
    let extra_len = u16::from_le_bytes([bytes[28], bytes[29]]) as usize;
    let lzma_header = 30 + name_len + extra_len;
    // Layout: version(2) | props_len(2) | props(5) = [pb_lc_lp, dict_le(4)]
    let dict_at = lzma_header + 5;
    bytes[dict_at..dict_at + 4].copy_from_slice(&0xF000_0000u32.to_le_bytes());

    let mut archive = Archive::new(Cursor::new(bytes)).expect("the archive still parses");
    let error = archive
        .read_entry(0)
        .expect_err("an absurd dictionary must be refused");
    let message = error.to_string();
    assert!(
        message.contains("dictionary") && message.contains("limit"),
        "the error should explain the refusal: {message}"
    );
}

