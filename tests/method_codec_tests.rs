//! Real archives using method 9 (Deflate64), 14 (LZMA) and 98 (PPMd), produced by 7-Zip 25.01.
//!
//! These methods are relatively rare, and a decoder that silently produces garbage is worse than
//! one that refuses: the CRC-32 check is what makes these tests meaningful, because it fails if
//! the decoded bytes are wrong in any way.
//!
//! Regenerate with:
//!   7z a -tzip -mm=Deflate64 out.zip payload.txt
//!   7z a -tzip -mm=LZMA      out.zip payload.txt
//!   7z a -tzip -mm=PPMd      out.zip payload.txt

use std::io::Cursor;
#[allow(unused_imports)]
use std::io::Read;
use zipcore::{Archive, Compression, Error};

/// The archive's single entry must decode to a repeating "Line N of a repetitive corpus" text.
#[allow(dead_code)]
fn check_decoded(archive_bytes: &[u8], expected_method: u16) {
    let mut archive =
        Archive::new(Cursor::new(archive_bytes.to_vec())).expect("the archive must parse");
    let entry = archive.entries().first().expect("one entry");
    assert_eq!(entry.method(), expected_method, "unexpected method id");

    let data = archive.read_entry(0).expect("the entry must decode");
    // 400 lines of that sentence, so check the shape rather than embedding 30 KB of text.
    assert_eq!(data.len(), 29_890, "unexpected decoded length");
    let text = String::from_utf8(data).expect("payload is UTF-8");
    assert!(
        text.starts_with("Line 0 of a repetitive corpus"),
        "{:?}",
        &text[..40]
    );
    assert!(
        text.contains("Line 399 of a repetitive corpus"),
        "payload is truncated"
    );
    // Reading it again must give the same answer.
    assert_eq!(archive.read_entry(0).unwrap().len(), 29_890);
}

